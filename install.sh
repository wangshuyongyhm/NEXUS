#!/usr/bin/env bash
# NEXUS install.sh — DRAFT (skeleton phase).
#
# Scope (draft): dependency detection → config generation → service registration.
# Platforms: macOS (launchd) implemented as draft; Linux (systemd --user) = TODO
# seams marked below. OCRX (macOS-only) is NOT part of the core install.
#
# The installer is idempotent and stops with a clear message at the
# "missing real configuration" boundary (that is expected for the skeleton).
set -euo pipefail

NEXUS_HOME="${NEXUS_HOME:-$HOME/.nexus}"
CONFIG="$NEXUS_HOME/config.toml"
PG_DSN="${NEXUS_PG_DSN:-postgresql://localhost:6432/nexus_mem}"  # via pgbouncer
MODEL_DIR="${NEXUS_MODEL_DIR:-$HOME/.cache/huggingface/hub}"

say()  { printf '%s\n' "$*"; }
ok()   { say "  ✅ $*"; }
warn() { say "  ⚠️  $*"; }
die()  { say "  ❌ $*" >&2; exit 1; }

say "=== NEXUS install (draft) ==="

# ── 1. dependency detection ──────────────────────────────────────────────
say "→ [1/6] dependencies"
# Task1583: 多候选探测（1581 实证：本机 python3 默认指向 3.14 双通道全灭，
# 而 python3.11 显式二进制存在——只探测 python3 = 新用户第一脚必死）。
# 优先 NEXUS_PYTHON 覆盖，其次显式版本二进制，最后裸 python3。
PYFOUND=""
_py_ok() {  # $1=候选命令/路径
  command -v "$1" >/dev/null 2>&1 || [ -x "$1" ] || return 1
  "$1" -c 'import sys; exit(0 if (3,10) <= sys.version_info[:2] < (3,12) else 1)' 2>/dev/null
}
for cand in ${NEXUS_PYTHON:-} python3.11 python3.10 /opt/homebrew/bin/python3.11 /opt/homebrew/bin/python3.10 python3; do
  [ -n "$cand" ] && _py_ok "$cand" && { PYFOUND="$cand"; break; }
done
if [ -z "$PYFOUND" ]; then
  say "  ❌ 未找到 Python >=3.10,<3.12（torch 在 3.14 挂起是实证约束）" >&2
  say "     修复任选：brew install python@3.11 / pyenv install 3.11.6 /" >&2
  say "     已有合适解释器则：NEXUS_PYTHON=/path/to/python3.11 ./install.sh" >&2
  exit 1
fi
PYV=$("$PYFOUND" -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
ok "python $PYV ($PYFOUND)"
command -v psql >/dev/null || die "psql not found（brew install postgresql@15 && brew install pgvector）"
PSQL_V=$(psql --version | grep -oE '[0-9]+' | head -1)
[ "${PSQL_V:-0}" -ge 15 ] && ok "psql $PSQL_V" || warn "psql 版本 $PSQL_V < 15（建议 postgresql@15）"
psql -tAc "SELECT 1" "postgresql://localhost/postgres" >/dev/null 2>&1 \
  && ok "PostgreSQL reachable" || warn "PostgreSQL not reachable yet (start it before step 4)"
say "  ℹ️  pgvector 需自行确认：psql -d nexus_mem -c \"CREATE EXTENSION IF NOT EXISTS vector\"（brew install pgvector）"
command -v pgbouncer >/dev/null && ok "pgbouncer" || warn "pgbouncer missing (brew install pgbouncer)"
command -v fswatch >/dev/null && ok "fswatch (optional accelerator)" || warn "fswatch missing (optional; embed falls back to polling)"

# ── 2. python packages ───────────────────────────────────────────────────
say "→ [2/6] packages (editable, skeleton phase uses --no-deps for speed)"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 专用 venv——绝不用 ambient python3（1575 实战坑：装进 pyenv 全局会影子覆盖
# 已注册的同名 editable 包，生产服务静默换芯）
VENV="$NEXUS_HOME/venv"
[ -x "$VENV/bin/python3" ] || { "$PYFOUND" -m venv "$VENV"; ok "venv created: ${VENV}（解释器 ${PYFOUND}）"; }
PYB="$VENV/bin/python3"
"$PYB" -m pip install -e "$SCRIPT_DIR" --no-deps -q && ok "nexus-oss (meta)"
for p in nexus-gatekit nexus-mem nexus-xdr; do
  "$PYB" -m pip install -e "$SCRIPT_DIR/packages/$p" --no-deps -q && ok "$p"
done
say "  (full deps: $VENV/bin/pip install -e 'packages/nexus-mem[full]' — downloads torch+BGE, ~5GB)"

# ── 3. model weights (optional, embed service only) ──────────────────────
say "→ [3/6] BGE-M3 model weights (~4.3GB, optional)"
if [ -d "$MODEL_DIR" ]; then ok "model dir exists: $MODEL_DIR"; else warn "model dir missing; embed service needs: huggingface-cli download BAAI/bge-m3 BAAI/bge-reranker-v2-m3"; fi

# ── 4. database ──────────────────────────────────────────────────────────
say "→ [4/6] database"
say "  manual step (draft): createdb nexus_mem && psql -d nexus_mem -c 'CREATE EXTENSION vector'"
say "  then apply db/schema.sql + db/migrations/00*.sql in order（本仓 db/ 已含脱敏基线+迁移）"

# ── 5. config generation ─────────────────────────────────────────────────
say "→ [5/6] config"
mkdir -p "$NEXUS_HOME"
if [ ! -f "$CONFIG" ]; then
  cat > "$CONFIG" <<TOML
# NEXUS configuration (generated by install.sh draft)
vault_root = ""            # REQUIRED: path of your Obsidian-style vault
pg_dsn = "$PG_DSN"
model_dir = "$MODEL_DIR"
[ports]
mem = 11537
embed = 11436
xdr = 19998
console = 19900
rerank = 11437
TOML
  chmod 600 "$CONFIG"
  ok "wrote $CONFIG"
else
  ok "config exists: $CONFIG"
fi

# ── 6. service registration ──────────────────────────────────────────────
say "→ [6/6] service registration"
case "$(uname -s)" in
  Darwin)
    say "  macOS: launchd plists would be generated from templates/launchd/*.plist"
    say "  with __NEXUS_HOME__/__PYTHON_BIN__ placeholders substituted here."
    say "  NOTE: macOS TCC requires manually granting Full Disk Access to the"
    say "  python binary used by launchd jobs (System Settings → Privacy)."
    ;;
  Linux)
    say "  TODO(linux): systemd --user units — translation layer not built yet."
    say "  Seam: everything above is platform-neutral; only this step differs."
    ;;
  *) warn "unknown platform $(uname -s) — services not registered" ;;
esac

if grep -q 'vault_root = ""' "$CONFIG"; then
  say ""
  say "== skeleton boundary reached =="
  say "Edit $CONFIG (set vault_root), then re-run ./install.sh."
  exit 2
fi
say "== install draft complete =="
